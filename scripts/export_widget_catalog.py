"""Writes the ready-made My Day panels that need no Claude into apps/web/src/core/localCatalog.generated.ts.

The standalone phone app has no server, so it carries its own copy of the catalog. It is generated from apps/api/aios/widgets.py (never typed
by hand), and tests/test_widget_catalog.py fails if the committed file is out of date.

Usage:  .venv\\Scripts\\python.exe scripts\\export_widget_catalog.py"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "apps" / "api"))

from aios import widgets  # noqa: E402

OUT = ROOT / "apps" / "web" / "src" / "core" / "localCatalog.generated.ts"
HEADER = ("// GENERATED by scripts/export_widget_catalog.py from apps/api/aios/widgets.py. Do not edit by hand.\n"
          "// Panels that need Claude (routines) are left out: the standalone app has no Claude.\n")


def build() -> str:
    items = [t for t in widgets.CATALOG if not t["needs_claude"] and t["kind"] != "routine"]
    groups = [g for g in widgets.GROUPS if any(t["group"] == g for t in items)]
    body = json.dumps({"groups": groups, "items": items}, indent=2, ensure_ascii=False)
    return f"{HEADER}export const LOCAL_CATALOG = {body} as const;\n"


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
